package com.example.tgbot.domain.enums;

/**
 * Статус записи генерации в истории операций.
 */
public enum GenerationStatus {
    /** Запрос на генерацию отправлен */
    REQUESTED,
    /** Получен task_id, генерация в процессе */
    PROCESSING,
    /** Успешно получены ссылки на контент */
    SUCCESS,
    /** Ошибка на этапе запроса или получения результата */
    FAILED,
    /** Запись удалена пользователем (не отображается в интерфейсе, учитывается в расчётах) */
    DELETED
}
